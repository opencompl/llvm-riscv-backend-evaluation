#include <stdint.h>
#include <stdio.h>

#include <gem5/m5ops.h>

#define ITERATIONS 1024

/* RFC 8439, section 2.3.2 test vector. */
static const uint8_t key[32] = {
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
    0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
    0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
};

static const uint8_t nonce[12] = {
    0x00, 0x00, 0x00, 0x09, 0x00, 0x00,
    0x00, 0x4a, 0x00, 0x00, 0x00, 0x00,
};

static const uint8_t expected[64] = {
    0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15,
    0x50, 0x0f, 0xdd, 0x1f, 0xa3, 0x20, 0x71, 0xc4,
    0xc7, 0xd1, 0xf4, 0xc7, 0x33, 0xc0, 0x68, 0x03,
    0x04, 0x22, 0xaa, 0x9a, 0xc3, 0xd4, 0x6c, 0x4e,
    0xd2, 0x82, 0x64, 0x46, 0x07, 0x9f, 0xaa, 0x09,
    0x14, 0xc2, 0xd7, 0x05, 0xd9, 0x8b, 0x02, 0xa2,
    0xb5, 0x12, 0x9c, 0xd1, 0xde, 0x16, 0x4e, 0xb9,
    0xcb, 0xd0, 0x83, 0xe8, 0xa2, 0x50, 0x3c, 0x4e,
};

static uint8_t output[64];
static uint32_t state[16];
static uint32_t working_state[16];

extern void chacha20_block(const uint8_t *key, uint32_t counter,
                           const uint8_t *nonce, uint8_t *out,
                           uint32_t *state, uint32_t *working_state);

int
main(void)
{
    m5_reset_stats(0, 0);
    for (int i = 0; i < ITERATIONS; i++) {
        chacha20_block(key, 1, nonce, output, state, working_state);
    }
    m5_dump_stats(0, 0);

    int mismatches = 0;
    uint64_t hash = 1469598103934665603ULL;
    for (int i = 0; i < 64; i++) {
        if (output[i] != expected[i]) {
            mismatches++;
        }
        hash ^= output[i];
        hash *= 1099511628211ULL;
    }

    printf("CHECKSUM: 0x%016llx\n", (unsigned long long)hash);
    return mismatches;
}
